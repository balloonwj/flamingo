-- v6_add_t_chatmsg_idx_to_msgid.sql
--
-- 为 t_chatmsg 增加索引 idx_to_msgid (f_to, f_msgid)。
-- 已存在的库需手工执行本脚本；新库由 table.sql 的建表语句、以及 MysqlManager.cpp
-- 里那份运行期建表定义直接带上，无需再跑本脚本。
-- 注意 CMysqlManager::checkTable 只会自动 ALTER ADD COLUMN 补缺失的列，
-- **不会**补索引，所以存量库只能靠本脚本升级。
--
-- 为什么要这条索引：拉会话列表（cmd_sync_conversations）时要按会话取"最后一条消息"，
-- 查询形如
--     SELECT f_to, MAX(f_msgid) FROM t_chatmsg
--      WHERE f_ctype = 2 AND f_to IN (...) AND <排除本人已删除的> GROUP BY f_to
-- 本索引让它按 (f_to, f_msgid) 逐组直接跳到最大值。没有它，数据库就得把这些会话的
-- 全部消息扫一遍再分组，于是聊天记录越攒越多、登录越来越慢。
--
-- 既有的 idx_to_from (f_to, f_from) 顶不上：它的第二列是 f_from，同一个会话内
-- f_msgid 是散的，取最大值仍要扫完整个会话。
--
-- 实测（2026-08-12，25 万行 / 50 个群，见 docs/会话列表拉取性能优化方案.md）：
--     SQLite  1046 ms → 68 ms
--     MySQL    583 ms → 303 ms
-- 两种后端都确实需要它。
--
-- 【一段值得记下的弯路】最初只在 MySQL 上用<u>旧的</u>查询形状
-- （逐会话 ORDER BY f_msgid DESC LIMIT 1）做过对比，那种形状下 MySQL 靠 idx_to_from
-- 隐含的主键列就够了，加索引反而略慢，于是一度判定"MySQL 不需要这条索引"。
-- 实际代码在批量化改造后已改成上面的 GROUP BY 形状，对索引的需求完全不同。
-- 教训：换了查询写法就要重新测，别拿旧形状的结论套新代码。
--
-- SQLite 后端不需要执行本脚本：其索引定义在 sqliteapi/SqliteSchema.cpp 里
-- （由 tools/gen_table_sqlite.py 从 table.sql 生成），CSqliteManager::init 每次启动时
-- 以 CREATE INDEX IF NOT EXISTS 重放，存量库会被自动补上。
--
-- balloonwj@qq.com   2026-08-12

-- 消息表通常是全库最大的表，建索引期间会持有表锁并占用磁盘 IO，
-- 请在低峰期执行；执行时长与 t_chatmsg 的行数成正比。
ALTER TABLE t_chatmsg ADD KEY idx_to_msgid (f_to, f_msgid);
